"""Generates tests/fixtures.hpp: input series plus statsmodels' own answers.

The C++ cointegration code is a reimplementation of
statsmodels.tsa.stattools.coint, and that is a place where being quietly a
little wrong is worse than crashing - a slightly-off p-value does not fail, it
just calls unrelated series cointegrated. So statsmodels is pinned here as the
oracle rather than the numbers being eyeballed.

Every series is SYNTHETIC and generated from a seeded RNG. That is deliberate:
market data from the usual free providers is licensed for personal use and may
not be redistributed, so a public repository cannot carry it. Seeded synthetic
series are also reproducible by anyone, which committed price history is not.

The cases are chosen so the ADF lag search (AIC) selects a DIFFERENT number of
lags in each - otherwise the tests would only ever cover one path through it.

    python tools/gen_fixtures.py

Requires numpy and statsmodels. The generated header is committed, so building
and running the tests needs neither.
"""
import os

import numpy as np
import statsmodels
from statsmodels.regression.linear_model import OLS
from statsmodels.tsa.stattools import adfuller, coint

N = 400


def cases():
    rng = np.random.default_rng(7)

    # 1. Genuinely cointegrated: a shared stochastic trend plus a stationary
    #    spread. Must come out well under any sane alpha.
    common = np.cumsum(rng.normal(0, 1, N))
    a = 100 + common + rng.normal(0, 0.5, N)
    b = 50 + 0.5 * common + rng.normal(0, 0.5, N)
    yield "cointegrated", np.log(a - a.min() + 10), np.log(b - b.min() + 10)

    # 2. Two independent random walks. Must NOT come out cointegrated - this is
    #    the false positive the significance test exists to reject.
    x = 100 + np.cumsum(rng.normal(0, 1, N))
    y = 100 + np.cumsum(rng.normal(0, 1, N))
    yield "independent", np.log(x - x.min() + 10), np.log(y - y.min() + 10)

    # 3. Cointegrated, but with autocorrelated spread noise, which drives the
    #    AIC lag search to a different selection than case 1.
    common2 = np.cumsum(rng.normal(0, 1, N))
    noise = np.zeros(N)
    e = rng.normal(0, 0.4, N)
    for i in range(1, N):
        noise[i] = 0.7 * noise[i - 1] + e[i]
    c = 200 + common2 + noise
    d = 80 + 0.75 * common2 + rng.normal(0, 0.3, N)
    yield "autocorrelated", np.log(c - c.min() + 10), np.log(d - d.min() + 10)


def carr(name, values):
    # float(v) first: numpy 2.x reprs a scalar as "np.float64(1.23)", which is
    # valid Python and not remotely valid C++.
    values = [float(v) for v in values]
    body = ",\n    ".join(", ".join(f"{v!r}" for v in values[i:i + 6]) for i in range(0, len(values), 6))
    return f"inline constexpr double {name}[] = {{\n    {body}\n}};"


out = [
    f"// GENERATED by tools/gen_fixtures.py from statsmodels {statsmodels.__version__}.",
    "// Expected values are statsmodels' own output - it is the oracle for this",
    "// reimplementation, not a rough guide. Do not hand-edit.",
    "//",
    "// All series are synthetic and seeded: this repository carries no market",
    "// data, which is a licensing matter as much as a reproducibility one.",
    "#pragma once",
    "",
    "namespace tb::fixtures {",
    "",
]

selected_lags = {}
for name, y0, y1 in cases():
    stat, pval, _ = coint(y0, y1, trend="c", method="aeg", maxlag=None, autolag="aic")
    st1 = OLS(y0, np.column_stack([y1, np.ones_like(y1)])).fit()
    adf = adfuller(st1.resid, maxlag=None, autolag="aic", regression="n")
    selected_lags[name] = int(adf[2])
    out += [
        carr(f"{name}_y0", y0),
        carr(f"{name}_y1", y1),
        f"inline constexpr double {name}_coint_stat = {float(stat)!r};",
        f"inline constexpr double {name}_coint_pvalue = {float(pval)!r};",
        f"inline constexpr double {name}_hedge_ratio = {float(st1.params[0])!r};",
        f"inline constexpr double {name}_intercept = {float(st1.params[1])!r};",
        f"inline constexpr double {name}_adf_stat = {float(adf[0])!r};",
        f"inline constexpr int {name}_adf_usedlag = {int(adf[2])};",
        f"inline constexpr double {name}_correlation = {float(np.corrcoef(y0, y1)[0, 1])!r};",
        "",
    ]

# A plain OLS case with statsmodels' coefficients AND standard errors. The
# standard errors matter more than usual here: the ADF statistic is a t-value,
# so an error in bse is an error in every p-value the library reports.
rng = np.random.default_rng(11)
n = 120
x1 = rng.normal(0, 1, n)
x2 = rng.normal(0, 1, n)
yv = 3.0 + 2.0 * x1 - 1.5 * x2 + rng.normal(0, 0.3, n)
fit = OLS(yv, np.column_stack([np.ones(n), x1, x2])).fit()
out += [
    carr("ols_y", yv),
    carr("ols_x1", x1),
    carr("ols_x2", x2),
    carr("ols_params", fit.params),
    carr("ols_bse", fit.bse),
    f"inline constexpr double ols_sigma2 = {float(fit.mse_resid)!r};",
    "",
    "}  // namespace tb::fixtures",
]

path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests", "fixtures.hpp")
with open(path, "w", encoding="utf-8") as f:
    f.write("\n".join(out) + "\n")

print("wrote", os.path.normpath(path))
print("AIC-selected lags per case:", selected_lags)
if len(set(selected_lags.values())) < 2:
    print("WARNING: every case selected the same lag count - the lag search is no "
          "longer meaningfully covered; adjust a case.")
